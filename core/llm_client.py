"""Модуль взаимодействия с языковой моделью (LLM).

Ответственный разработчик: Разработчик 4 (Интеграция с LLM и промпты)
Задача:
1. Сформировать системный промпт с правилами (строго по контексту, указывать источник).
2. Отправить контекст и вопрос студента в API нейросети (GigaChat / YandexGPT / OpenAI).
3. Вернуть сформулированный ответ.
"""

import os
from typing import List
from dotenv import load_dotenv
from core import Chunk

load_dotenv()

SYSTEM_PROMPT = """Ты — официальный ИИ-ассистент первокурсника Московского Политеха.
Твоя задача — отвечать на вопросы студентов СТРОГО на основе предоставленных фрагментов документов.

ПРАВИЛА:
1. Используй ТОЛЬКО факты из переданного контекста. Ничего не придумывай от себя.
2. Всегда в конце ответа указывай источник информации (название документа и страницу, если есть).
3. Если в переданных фрагментах НЕТ точного ответа на вопрос:
   - Честно напиши: "К сожалению, в официальных документах нет ответа на этот вопрос."
   - Подскажи студенту, в какую службу обратиться (Студенческий офис, деканат, профком).
"""


class LLMClient:
    def __init__(self):
        self.api_key = os.getenv("LLM_API_KEY", "")

    def generate_answer(self, query: str, context_chunks: List[Chunk]) -> str:
        """Генерация ответа по найденному контексту."""
        if not context_chunks:
            return (
                "К сожалению, в базе знаний нет информации по вашему вопросу.\n\n"
                "📌 Рекомендуем обратиться в **Студенческий офис** Московского Политеха."
            )

        # Собираем контекст из найденных фрагментов
        context_text = "\n\n---\n\n".join(
            [f"[Источник: {c.source}" + (f", стр. {c.page}]" if c.page else "]") + f"\n{c.text}"
             for c in context_chunks]
        )

        # Если API-ключ не настроен, отдаем информативную заглушку для локальной отладки
        if not self.api_key:
            sources = ", ".join(set([c.source for c in context_chunks]))
            return (
                f"*(Режим отладки: API_KEY не задан в .env)*\n\n"
                f"По вашему вопросу найдена информация в следующих документах:\n"
                f"**{sources}**\n\n"
                f"**Фрагмент текста:**\n> {context_chunks[0].text[:350]}...\n\n"
                f"*(Подключите реальный API-ключ в .env для генерации связного ответа через нейросеть)*"
            )

        # TODO: Реализовать вызов реального API (GigaChat / YandexGPT)
        return "Здесь будет реальный ответ от модели."
